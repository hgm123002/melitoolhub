"use client";

import { useState } from "react";
import ToolLayout from "../../../../../components/ai-workbench/ToolLayout";
import TextPanel from "../../../../../components/ai-workbench/TextPanel";
import FileUploader from "../../../../../components/ai-workbench/FileUploader";
import {
  ActionButton,
  StatusBar,
  
} from "../../../../../components/ai-workbench/ActionButton";
import { useAI } from "../../../../../components/ai-workbench/useAI";
import { AIStatusControl } from "../../../../../components/ai-workbench/AISettings";
import { BookOpen, Download, FileText, Sparkles } from "lucide-react";

export default function PdfSummaryPage() {
  const { service, apiKey, loading, error, result, process, reset, aiReady } =
    useAI() as any;
  const [files, setFiles] = useState<any[]>([]);
  const [summaryRatio, setSummaryRatio] = useState<string>("detailed");
  const [copied, setCopied] = useState<boolean>(false);

  const handleProcess = async () => {
    if (!files || files.length === 0) return;
    const fileNames = files.map((f) => f.name);
    await process("PDF解析", {
      task: "pdf-parse",
      service,
      apiKey,
      files: fileNames,
      ratio: summaryRatio,
    });
  };

  const textResult =
    typeof result === "string" ? result : result?.summary || result?.text || "";
  const isMock = !aiReady;

  const downloadMarkdown = () => {
    if (!textResult) return;
    const content =
      "# 文档批量AI归纳报告\n\n" +
      textResult +
      "\n\n---\n*Generated by GlobalTradeHub AI Workbench*";
    const blob = new Blob([content], { type: "text/markdown;charset=utf-8" });
    const url = URL.createObjectURL(blob);
    const a = document.createElement("a");
    a.href = url;
    a.download = "AI归纳报告.md";
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <ToolLayout
      title="PDF批量AI归纳"
      icon={BookOpen}
      description="批量上传PDF文档,AI自动解析内容、生成摘要、合并汇总、产出结构化报告"
    >
      <div className="space-y-5">
        <section className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5">
          <h3 className="text-sm font-semibold text-[#1e3a5f] mb-3 flex items-center gap-2">
            <Sparkles className="w-4 h-4" />
            摘要详细程度
          </h3>
          <div className="grid grid-cols-3 gap-3">
            {[
              {
                id: "brief",
                name: "精简版",
                desc: "核心要点和结论",
                icon: "📋",
              },
              {
                id: "detailed",
                name: "详细版",
                desc: "完整内容提取",
                icon: "📚",
              },
              {
                id: "report",
                name: "结构化报告",
                desc: "章节、关键词、图表",
                icon: "📊",
              },
            ].map((m) => (
              <button
                key={m.id}
                onClick={() => {
                  setSummaryRatio(m.id);
                  reset();
                }}
                className={
                  "p-4 rounded-xl border text-left transition " +
                  (summaryRatio === m.id
                    ? "border-[#1e3a5f] bg-blue-50 text-[#1e3a5f]"
                    : "border-gray-200 hover:border-gray-300 bg-white")
                }
              >
                <div className="text-xl mb-2">{m.icon}</div>
                <div className="text-sm font-bold">{m.name}</div>
                <div className="text-xs text-gray-500 mt-1">{m.desc}</div>
              </button>
            ))}
          </div>
        </section>

        <section className="bg-white rounded-2xl shadow-sm border border-gray-100 p-5">
          <h3 className="text-sm font-semibold text-[#1e3a5f] mb-3">
            上传文档 (PDF / Word / 图片)
          </h3>
          <FileUploader
            files={files}
            onFilesChange={setFiles}
            accept=".pdf,.doc,.docx,.jpg,.jpeg,.png"
            multiple={true}
            maxFiles={20}
            maxSize={100}
          />
        </section>

        <div className="flex items-center justify-between">
          <div className="text-xs text-gray-500">
            <span className="text-gray-500 mr-2">
              已选择 {files.length} 个文档
            </span>
            <AIStatusControl />
          </div>
          <ActionButton
            onClick={handleProcess}
            disabled={files.length === 0}
            loading={loading}
            label="开始归纳"
          />
        </div>

        <StatusBar
          loading={loading}
          error={error}
          isMock={isMock}
          result={result}
        />

        {textResult && (
          <div className="space-y-3">
            <div className="flex items-center gap-2 justify-end">
              <button
                onClick={downloadMarkdown}
                className="px-4 py-2 text-sm bg-[#1e3a5f] text-white rounded-xl flex items-center gap-2 hover:shadow-lg"
              >
                <Download className="w-4 h-4" />
                下载 Markdown
              </button>
            </div>
            <TextPanel
              title="✅ 归纳报告"
              placeholder="AI生成的归纳报告将在此显示..."
              value={textResult}
              minHeight={400}
            />
          </div>
        )}
      </div>
    </ToolLayout>
  );
}
