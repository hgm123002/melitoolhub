// --- 语言包合并 ---
// zh-CN / en 是完整字典；其余 16 种语言的文案包在 ./locales 下，
// 合并优先级：当前语言字典 > 当前语言包 > 英文底稿（保证不出现 key 原文）。
const BASE_EN: Dictionary = TRANSLATIONS.en ?? {};

const DICT_CACHE: { [K in LanguageCode]?: Dictionary } = {};

const dictFor = (lang: LanguageCode): Dictionary => {
  const cached = DICT_CACHE[lang];
  if (cached) return cached;
  const own = TRANSLATIONS[lang] ?? {};
  const pack = LOCALE_PACKS[lang] ?? {};
  const merged: Dictionary =
    lang === "en" ? BASE_EN : { ...BASE_EN, ...pack, ...own };
  DICT_CACHE[lang] = merged;
  return merged;
};

// --- Context ---
type LanguageContextValue = {
  language: LanguageCode;
  setLanguage: (lang: LanguageCode) => void;
  t: (key: string, fallback?: string) => string;
  supportedLanguages: typeof SUPPORTED_LANGUAGES;
};

const LanguageContext = createContext<LanguageContextValue | null>(null);

export const LanguageProvider = ({
  children,
  initialLocale,
}: {
  children: React.ReactNode;
  /** 由 [locale] 路由从 URL 注入，是语言的唯一事实来源（SSR 与客户端一致） */
  initialLocale?: LanguageCode;
}) => {
  const [language, setLanguageState] = useState<LanguageCode>(
    initialLocale ?? DEFAULT_LANGUAGE,
  );

  // 语言由 URL /{locale}/ 决定，切换语言 = 跳转到对应 locale 前缀的 URL
  // （不再从 localStorage / 浏览器语言覆盖，避免 SSR 内容与实际语言不一致）

  const setLanguage = useCallback((lang: LanguageCode) => {
    setLanguageState(lang);
    // 同时写 cookie，供 middleware 未带 locale 前缀访问时做语言偏好检测
    try {
      document.cookie =
        "gth_language=" + lang + ";path=/;max-age=31536000;samesite=lax";
    } catch {}
    try {
      localStorage.setItem("gth_language", lang);
    } catch {}
    try {
      const entry = SUPPORTED_LANGUAGES.find((l) => l.code === lang);
      document.documentElement.dir = entry?.dir === "rtl" ? "rtl" : "ltr";
      document.documentElement.lang = lang;
    } catch {}
  }, []);

  const t = useCallback(
    (key: string, fallback?: string) => {
      try {
        const dict = dictFor(language);
        const hit = dict[key];
        if (hit) return hit;
      } catch {}
      return fallback ?? key;
    },
    [language],
  );

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        supportedLanguages: SUPPORTED_LANGUAGES,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => {
  const ctx = useContext(LanguageContext);
  if (!ctx) {
    return {
      language: DEFAULT_LANGUAGE,
      setLanguage: () => {},
      t: (key: string, fallback?: string) => fallback ?? key,
      supportedLanguages: SUPPORTED_LANGUAGES,
    };
  }
  return ctx;
};

export default LanguageContext;
