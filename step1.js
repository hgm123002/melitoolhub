'    result.push("【图片解析结果】\\n");',
'    result.push("处理文件数: " + fcount + " 个\\n");',
'    result.push("【识别到的文字内容】");',
'    result.push("  (本地模式模拟识别结果)");',
'    result.push("  1. 图片整体结构分析完成");',
